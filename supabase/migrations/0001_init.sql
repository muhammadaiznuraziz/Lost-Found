create or replace function public.log_claim_created()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_owner uuid;
  v_report_number varchar(30);
begin
  select user_id, report_number into v_owner, v_report_number
  from public.item_reports where id = new.item_report_id;

  insert into public.claim_status_history (claim_id, old_status, new_status, changed_by, reason)
  values (new.id, null, 'PENDING', new.claimant_id, 'Klaim baru diajukan');

  insert into public.notifications (user_id, title, message, notification_type, related_report_id, related_claim_id)
  values (
    v_owner,
    'Ada klaim baru',
    'Klaim ' || new.claim_number || ' diajukan untuk laporan ' || coalesce(v_report_number, ''),
    'CLAIM_CREATED',
    new.item_report_id,
    new.id
  );
  return new;
end;
$$;

